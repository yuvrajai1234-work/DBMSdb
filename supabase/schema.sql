-- ===================================================================
-- LumiSafeDB · PostgreSQL schema (Supabase)
-- 8 core relational tables + 2 specialization (IS-A) subtype tables.
-- The server applies this file automatically at startup; you can also
-- paste it into the Supabase SQL Editor.
-- ===================================================================

CREATE TABLE IF NOT EXISTS electricaldivisions (
  div_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  div_name    VARCHAR(100) NOT NULL,
  district    VARCHAR(50)  NOT NULL,
  CONSTRAINT uq_division UNIQUE (div_name, district)
);

CREATE TABLE IF NOT EXISTS wardcouncils (
  ward_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  div_id          INTEGER NOT NULL,
  ward_name       VARCHAR(100) NOT NULL,
  councillor_name VARCHAR(100) NOT NULL,
  CONSTRAINT fk_ward_division FOREIGN KEY (div_id)
    REFERENCES electricaldivisions(div_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT uq_ward UNIQUE (div_id, ward_name)
);

CREATE TABLE IF NOT EXISTS lightpoles (
  pole_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  div_id       INTEGER NOT NULL,
  pole_name    VARCHAR(50) NOT NULL,
  latitude     DECIMAL(10,8),
  longitude    DECIMAL(11,8),
  is_high_risk BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT uq_pole_name UNIQUE (pole_name),
  CONSTRAINT ck_latitude  CHECK (latitude  IS NULL OR (latitude  >= -90  AND latitude  <= 90)),
  CONSTRAINT ck_longitude CHECK (longitude IS NULL OR (longitude >= -180 AND longitude <= 180)),
  CONSTRAINT fk_pole_division FOREIGN KEY (div_id)
    REFERENCES electricaldivisions(div_id) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Specialization subtype: solar powered poles
CREATE TABLE IF NOT EXISTS solarlightpoles (
  pole_id INTEGER PRIMARY KEY,
  CONSTRAINT fk_solar_pole FOREIGN KEY (pole_id)
    REFERENCES lightpoles(pole_id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Specialization subtype: grid powered poles
CREATE TABLE IF NOT EXISTS electricallightpoles (
  pole_id INTEGER PRIMARY KEY,
  CONSTRAINT fk_electrical_pole FOREIGN KEY (pole_id)
    REFERENCES lightpoles(pole_id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS citizens (
  user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ward_id       INTEGER NOT NULL,
  first_name    VARCHAR(50)  NOT NULL,
  last_name     VARCHAR(50)  NOT NULL,
  email         VARCHAR(100) NOT NULL,
  phone_no      VARCHAR(15)  NOT NULL,
  date_of_birth DATE         NOT NULL,
  password_hash TEXT         NOT NULL,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT uq_citizen_email UNIQUE (email),
  CONSTRAINT uq_citizen_phone UNIQUE (phone_no),
  CONSTRAINT fk_citizen_ward FOREIGN KEY (ward_id)
    REFERENCES wardcouncils(ward_id) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS electricalofficials (
  official_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  div_id         INTEGER NOT NULL,
  official_name  VARCHAR(50)  NOT NULL,
  designation    VARCHAR(100) NOT NULL,
  official_email VARCHAR(100) NOT NULL,
  password_hash  TEXT         NOT NULL,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT uq_official_email UNIQUE (official_email),
  CONSTRAINT fk_official_division FOREIGN KEY (div_id)
    REFERENCES electricaldivisions(div_id) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS lightcomplaints (
  complaint_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER NOT NULL,
  pole_id      INTEGER NOT NULL,
  issue_type   VARCHAR(100) NOT NULL,
  priority     VARCHAR(20)  NOT NULL,
  status       VARCHAR(30)  NOT NULL DEFAULT 'Open',
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT ck_priority CHECK (priority IN ('Low','Medium','High','Critical')),
  CONSTRAINT ck_status   CHECK (status   IN ('Open','In Progress','Resolved','Closed')),
  CONSTRAINT fk_complaint_citizen FOREIGN KEY (user_id)
    REFERENCES citizens(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_complaint_pole FOREIGN KEY (pole_id)
    REFERENCES lightpoles(pole_id) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Weak entity: identified by (complaint_id, media_url)
CREATE TABLE IF NOT EXISTS complaintmedia (
  complaint_id INTEGER NOT NULL,
  media_url    VARCHAR(255) NOT NULL,
  uploaded_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (complaint_id, media_url),
  CONSTRAINT fk_media_complaint FOREIGN KEY (complaint_id)
    REFERENCES lightcomplaints(complaint_id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS vendors (
  vendor_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_name  VARCHAR(100) NOT NULL UNIQUE,
  service_type VARCHAR(150) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS workorders (
  work_order_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id   INTEGER NOT NULL,
  official_id    INTEGER,
  vendor_id      INTEGER,
  vendor_name    VARCHAR(100)  NOT NULL DEFAULT 'Unassigned',
  issued_date    DATE          NOT NULL DEFAULT CURRENT_DATE,
  target_date    DATE,
  est_cost       DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  completed_date DATE,
  CONSTRAINT uq_workorder_complaint UNIQUE (complaint_id),
  CONSTRAINT ck_est_cost CHECK (est_cost >= 0),
  CONSTRAINT fk_workorder_complaint FOREIGN KEY (complaint_id)
    REFERENCES lightcomplaints(complaint_id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_workorder_official FOREIGN KEY (official_id)
    REFERENCES electricalofficials(official_id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_workorder_vendor FOREIGN KEY (vendor_id)
    REFERENCES vendors(vendor_id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_poles_div       ON lightpoles(div_id);
CREATE INDEX IF NOT EXISTS idx_wards_div       ON wardcouncils(div_id);
CREATE INDEX IF NOT EXISTS idx_complaint_pole  ON lightcomplaints(pole_id);
CREATE INDEX IF NOT EXISTS idx_complaint_user  ON lightcomplaints(user_id);
CREATE INDEX IF NOT EXISTS idx_complaint_state ON lightcomplaints(status, created_at);
CREATE INDEX IF NOT EXISTS idx_workorder_due   ON workorders(completed_date);
CREATE INDEX IF NOT EXISTS idx_citizen_email_lower ON citizens(lower(email));
CREATE INDEX IF NOT EXISTS idx_official_email_lower ON electricalofficials(lower(official_email));

-- -------------------------------------------------------------------
-- Triggers: a citizen's date of birth can never be in the future.
-- -------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_citizen_dob_guard() RETURNS trigger AS $$
BEGIN
  IF NEW.date_of_birth > CURRENT_DATE THEN
    RAISE EXCEPTION 'date_of_birth cannot be in the future';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_citizen_dob ON citizens;
CREATE TRIGGER trg_citizen_dob
BEFORE INSERT OR UPDATE OF date_of_birth ON citizens
FOR EACH ROW EXECUTE FUNCTION fn_citizen_dob_guard();

-- -------------------------------------------------------------------
-- Triggers: a pole can carry only one specialization subtype row.
-- -------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_solar_exclusive() RETURNS trigger AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM electricallightpoles WHERE pole_id = NEW.pole_id) THEN
    RAISE EXCEPTION 'pole already specialized as an electrical light pole';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION fn_electrical_exclusive() RETURNS trigger AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM solarlightpoles WHERE pole_id = NEW.pole_id) THEN
    RAISE EXCEPTION 'pole already specialized as a solar light pole';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_solar_exclusive ON solarlightpoles;
CREATE TRIGGER trg_solar_exclusive
BEFORE INSERT OR UPDATE ON solarlightpoles
FOR EACH ROW EXECUTE FUNCTION fn_solar_exclusive();

DROP TRIGGER IF EXISTS trg_electrical_exclusive ON electricallightpoles;
CREATE TRIGGER trg_electrical_exclusive
BEFORE INSERT OR UPDATE ON electricallightpoles
FOR EACH ROW EXECUTE FUNCTION fn_electrical_exclusive();

-- -------------------------------------------------------------------
-- Trigger: when a ticket is raised, automatically flag the pole as high risk
-- -------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_complaint_flag_pole_risk() RETURNS trigger AS $$
BEGIN
  UPDATE lightpoles
     SET is_high_risk = TRUE
   WHERE pole_id = NEW.pole_id;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_complaint_flag_pole_risk ON lightcomplaints;
CREATE TRIGGER trg_complaint_flag_pole_risk
AFTER INSERT ON lightcomplaints
FOR EACH ROW EXECUTE FUNCTION fn_complaint_flag_pole_risk();

-- -------------------------------------------------------------------
-- Trigger: when a ticket is raised, automatically issue a work order
-- -------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_complaint_auto_create_workorder() RETURNS trigger AS $$
BEGIN
  INSERT INTO workorders (complaint_id, issued_date, target_date, est_cost, completed_date)
  VALUES (NEW.complaint_id, CURRENT_DATE, NULL, 0.00, NULL)
  ON CONFLICT (complaint_id) DO NOTHING;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_complaint_auto_create_workorder ON lightcomplaints;
CREATE TRIGGER trg_complaint_auto_create_workorder
AFTER INSERT ON lightcomplaints
FOR EACH ROW EXECUTE FUNCTION fn_complaint_auto_create_workorder();

-- -------------------------------------------------------------------
-- Trigger: when a ticket is resolved, automatically fill completed_date
-- -------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_resolve_workorder_completion() RETURNS trigger AS $$
BEGIN
  IF NEW.status IN ('Resolved', 'Closed') AND (OLD.status IS NULL OR OLD.status NOT IN ('Resolved', 'Closed')) THEN
    UPDATE workorders
       SET completed_date = CURRENT_DATE
     WHERE complaint_id = NEW.complaint_id
       AND completed_date IS NULL;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_resolve_workorder_completion ON lightcomplaints;
CREATE TRIGGER trg_resolve_workorder_completion
AFTER UPDATE OF status ON lightcomplaints
FOR EACH ROW EXECUTE FUNCTION fn_resolve_workorder_completion();

-- -------------------------------------------------------------------
-- Reporting view joining every core table.
-- -------------------------------------------------------------------
DROP VIEW IF EXISTS vw_complaintdetail CASCADE;
CREATE VIEW vw_complaintdetail AS
SELECT
  c.complaint_id,
  c.user_id,
  c.pole_id,
  c.issue_type,
  c.priority,
  c.status,
  c.created_at,
  GREATEST(0, FLOOR(EXTRACT(EPOCH FROM (now() - c.created_at)) / 86400))::int AS days_open,
  p.pole_name,
  p.div_id,
  p.is_high_risk,
  p.latitude,
  p.longitude,
  d.div_name,
  d.district,
  w.ward_id,
  w.ward_name,
  w.councillor_name,
  ci.first_name || ' ' || ci.last_name AS citizen_name,
  ci.email    AS citizen_email,
  ci.phone_no AS citizen_phone,
  wo.work_order_id,
  wo.vendor_id,
  COALESCE(v.vendor_name, wo.vendor_name, 'Unassigned') AS vendor_name,
  wo.issued_date,
  wo.target_date,
  wo.est_cost,
  wo.completed_date,
  CASE
    WHEN wo.work_order_id IS NULL THEN 0
    WHEN c.status IN ('Resolved', 'Closed') THEN 0
    WHEN wo.target_date IS NULL THEN 0
    ELSE GREATEST(0, CURRENT_DATE - wo.target_date)
  END AS days_overdue,
  (SELECT COUNT(*) FROM complaintmedia m WHERE m.complaint_id = c.complaint_id)::int AS media_count
FROM lightcomplaints c
JOIN lightpoles          p  ON p.pole_id  = c.pole_id
JOIN electricaldivisions d  ON d.div_id   = p.div_id
JOIN citizens            ci ON ci.user_id = c.user_id
JOIN wardcouncils        w  ON w.ward_id  = ci.ward_id
LEFT JOIN workorders     wo ON wo.complaint_id = c.complaint_id
LEFT JOIN vendors        v  ON v.vendor_id = wo.vendor_id;

